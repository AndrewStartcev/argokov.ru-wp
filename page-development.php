<section class="development-section surface" id="faq" aria-labelledby="development-faq-title">

<header class="development-heading">

<div>

<p class="section-eyebrow">
Частые вопросы
</p>

<h2 id="development-faq-title">
О разработке сайта до начала проекта
</h2>

</div>

</header>

<div class="development-faq">

<details>

<summary>
Сколько стоит разработка сайта?<span>+</span>
</summary>

<p>
Стоимость зависит от числа и сложности страниц, индивидуальности дизайна, бизнес-логики, интеграций и готовности материалов. После короткого знакомства разбираем задачу и даём поэтапную оценку — без цены, придуманной до изучения проекта.
</p>

</details>

<details>

<summary>
Сколько времени занимает создание сайта?<span>+</span>
</summary>

<p>
Срок определяется составом работ и скоростью согласований. Небольшой сайт и интернет-магазин с интеграциями требуют разного процесса, поэтому календарный план формируем после структуры и списка функций.
</p>

</details>

<details>

<summary>
Можно заказать создание сайта под ключ?<span>+</span>
</summary>

<p>
Да. Берём на себя аналитику, структуру, прототипы, дизайн, разработку, интеграции, техническую SEO-подготовку, тестирование и запуск. От клиента нужны знания о бизнесе и своевременная обратная связь.
</p>

</details>

<details>

<summary>
На какой CMS будет работать сайт?<span>+</span>
</summary>

<p>
Подбираем технологию под задачу. Основной стек — WordPress, но работаем с 1С-Битрикс, WooCommerce, PHP-фреймворками и самописными системами. Если CMS не нужна, не навязываем её.
</p>

</details>

<details>

<summary>
Будет ли сайт готов к SEO-продвижению?<span>+</span>
</summary>

<p>
На старте закладываем понятную иерархию, индексируемый контент, метаданные, человекопонятные адреса, микроразметку, мобильную версию, скорость и аналитику. Позиции не обещаем заранее: на них влияют конкуренция, контент и дальнейшее продвижение.
</p>

</details>

<details>

<summary>
Что происходит после запуска?<span>+</span>
</summary>

<p>
Передаём доступы и инструкции, контролируем сайт после публикации и исправляем относящиеся к разработке замечания. При необходимости берём проект на техническую поддержку и дальнейшее развитие.
</p>

</details>

